/** Which host tool (or bootstrap channel) produced a payload — the category the citation allowlist keys on. */
export type EvidenceOrigin = (typeof EVIDENCE_ORIGINS)[number];

/** Task 7.4's allowlist: the only origins a finding may cite. Everything else is intent or policy. */
export const CITABLE_ORIGINS: ReadonlySet<EvidenceOrigin> = new Set<EvidenceOrigin>([
  'diffPage',
  'fileRange',
  'repositorySearch',
  'diffSearch',
  'attachment',
]);

export type EvidenceTrust = 'untrusted' | 'authoritative';

export const EVIDENCE_PRODUCERS = ['localGit', 'sample', 'provider', 'host'] as const;

/**
 * Which source actually produced a payload — task 10.1 of
 * `add-local-git-investigation`.
 *
 * Three of the four values are `InvestigationSourceKind`'s own
 * (`../domain/reviewRunSnapshot.ts`), deliberately the same words the member
 * snapshot records, so a coverage report, a limitation and a diagnostic all
 * name a source the same way rather than each inventing a label. `provider` is
 * among them for the records already on disk: nothing produces one now, because
 * no investigation reaches a forge. The fourth, `host`, is for the payloads no
 * investigation source ever sees: a reviewer's attachment and the host's own
 * derived intent.
 *
 * Why per record rather than per run: a changeset's members each have their own
 * object store, and a stored ledger can hold records written under an older
 * build, so a run still reports truthfully where each fact came from.
 */
export type EvidenceProducer = (typeof EVIDENCE_PRODUCERS)[number];

/**
 * Which source answers this origin, given the source the member's snapshot
 * recorded for investigation.
 *
 * Exhaustive on purpose, with no default arm: a new `EvidenceOrigin` must
 * state where its content comes from, and the alternative — falling through to
 * `provider` — is how a locally computed fact would quietly be attributed to a
 * forge that never served it.
 *
 * The split follows design D2 as the rule sharpened it: everything answerable
 * from two commits comes from the selected source — the four investigation
 * payloads *and* the `AGENTS.md` walk `resolvePolicy` runs, which reads a file
 * in the repository at the base revision. Only change-request and issue detail
 * stay with the connection, because neither is in the repository at all
 * (`harnessToolDispatcher.ts`'s `dispatchTargetFor`).
 */
export function evidenceProducerFor(origin: EvidenceOrigin, investigationSource: InvestigationSourceKind): EvidenceProducer {
  switch (origin) {
    case 'diffPage':
    case 'fileRange':
    case 'repositorySearch':
    case 'diffSearch':
      return investigationSource;
    case 'agentsPolicy':
      return investigationSource;
    case 'changeRequestDetail':
    case 'issueDetail':
      return 'provider';
    case 'attachment':
    case 'intent':
      return 'host';
    default: {
      const exhaustive: never = origin;
      return exhaustive;
    }
  }
}

/** One exact span the model saw — what a citation's path/range must fall inside. `side` exists only for diff positions. */
export interface EvidenceLocation {
  readonly path: string;
  readonly range: EvidenceRange;
  readonly side?: 'old' | 'new';
}

export interface EvidenceTruncation {
  /** A provider continuation exists (state `paginated`); the ledger never stores the cursor itself. */
  readonly hasContinuation: boolean;
  readonly knownRemainingUnits?: number;
}

export interface LedgerEvidenceSource extends EvidenceSource {
  readonly runId: RunId;
  readonly lineageId: LineageId;
  /** The attempt whose ledger holds this record — not necessarily the attempt that first fetched it (see `importedFromAttempt`). */
  readonly attempt: AttemptNumber;
  readonly memberId: string;
  readonly origin: EvidenceOrigin;
  readonly trust: EvidenceTrust;
  /**
   * The source that produced these exact bytes (task 10.1), derived inside
   * `append` from the origin and the member's recorded investigation source —
   * never supplied by a caller, so nothing can label a payload with a source
   * that did not serve it.
   */
  readonly producedBy: EvidenceProducer;
  /** Position in this ledger's append order, starting at 1. */
  readonly sequence: number;
  readonly locations: readonly EvidenceLocation[];
  readonly byteLength: number;
  readonly truncation?: EvidenceTruncation;
  /** Attachments only: the snapshot's digest of the full attachment content (D8 "bound to their snapshot digest"). */
  readonly snapshotContentDigest?: string;
  /** Present only on a record reused from a prior attempt through `importRetainedSource`. */
  readonly importedFromAttempt?: AttemptNumber;
  /**
   * These bytes were fetched but never shown to the model — see `EvidenceLedger.revoke`. The
   * record stays in append order with its digest and byte count intact, because it really was
   * fetched and really was charged to this attempt's evidence budget; what it loses is
   * `citable`, and with it any path from a citation to a finding.
   */
  readonly revoked?: boolean;
}

