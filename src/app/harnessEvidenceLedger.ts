function refuse(code: RegistrationRefusal, message: string): Refusal {
  return { ok: false, code, message };
}

function completenessOf<T>(result: InvestigationResult<T>): { completeness: EvidenceCompleteness; truncation?: EvidenceTruncation } | undefined {
  switch (result.state) {
    case 'complete':
      return { completeness: 'complete' };
    case 'paginated':
      return { completeness: 'paginated', truncation: { hasContinuation: true } };
    case 'truncated':
      return { completeness: 'truncated', truncation: { hasContinuation: false, knownRemainingUnits: result.knownRemainingUnits } };
    default:
      return undefined;
  }
}

/**
 * The citable spans a diff page carries in its own bytes, read from the patch
 * itself when the source named none.
 *
 * **The live failure this exists for.** A `DiffPage` declares `positions` as
 * "positions inside `patch` a citation can anchor to", and `registerDiffPage`
 * took a page's citable locations from that field alone. The only production
 * investigation source — `../localgit/localGitSource.ts` — returns
 * `positions: []` on every page, deliberately: a position per line would
 * multiply a 20,000-line page by a factor its declared byte bound does not
 * count. So every diff page in every real run held **zero** citable locations,
 * `../app/harnessCitations.ts`'s `resolveCitation` failed each primary citation
 * at `pathMismatch` ("Evidence ev_… did not return any content for <the very
 * path the page is of>"), and that failure is not repairable — so
 * `validateCandidate` rejected the candidate outright and never reached its own
 * location or verbatim-code checks. A live review of 245 changed files
 * submitted nine candidates and the host destroyed all nine. Every test that
 * exercised a diff page fabricated `positions` no source produces, which is why
 * this shipped green.
 *
 * The fix belongs here rather than in the source: the ledger already holds the
 * exact bytes, and one derivation here answers for every source instead of each
 * one re-walking its own patch.
 *
 * Spans come from the lines the parse actually produced, never from the `@@`
 * header's counts. That is the difference between a span the model was shown
 * and a span it was not: a page cut mid-hunk by pagination still carries the
 * header's full counts, and trusting them would make unshown lines citable —
 * exactly the guarantee this ledger exists to provide. One span per hunk per
 * side, new side first, because `locationContaining` returns the first
 * containing span and a citation that fits both sides is a citation about the
 * head state (`harnessSynthesisVerification.ts` reads `side` off the location
 * to cut its excerpt window).
 *
 * A continuation page (page 2+ of a diff over this source's 20,000-line /
 * 256KB bound) begins mid-hunk with no `@@` header, so `parseHunks` yields
 * nothing and the page stays uncitable, as it was before this existed. Known
 * and left: it needs the source to state the page's own span, and no diff of a
 * single file in this project's reviews has reached that bound.
 */
function diffPatchLocations(patch: string, newPath: string, oldPath: string): EvidenceLocation[] {
  const locations: EvidenceLocation[] = [];
  for (const hunk of parseHunks(patch)) {
    let newFirst: number | undefined;
    let newLast: number | undefined;
    let oldFirst: number | undefined;
    let oldLast: number | undefined;
    for (const line of hunk.lines) {
      if (line.newLine !== undefined) {
        newFirst ??= line.newLine;
        newLast = line.newLine;
      }
      if (line.oldLine !== undefined) {
        oldFirst ??= line.oldLine;
        oldLast = line.oldLine;
      }
    }
    if (newFirst !== undefined && newLast !== undefined) locations.push({ path: newPath, range: { startLine: newFirst, endLine: newLast }, side: 'new' });
    if (oldFirst !== undefined && oldLast !== undefined) locations.push({ path: oldPath, range: { startLine: oldFirst, endLine: oldLast }, side: 'old' });
  }
  return locations;
}

export function createEvidenceLedger(
  identity: EvidenceLedgerIdentity,
  members: readonly EvidenceLedgerMember[],
  options: EvidenceLedgerOptions = {},
): EvidenceLedger {
  if (members.length === 0) throw new Error('An evidence ledger needs at least one member.');
  const memberIds = new Set<string>();
  for (const member of members) {
    if (memberIds.has(member.memberId)) throw new Error(`Duplicate ledger member id: ${member.memberId}`);
    memberIds.add(member.memberId);
  }
  const policy = options.policy ?? DEFAULT_HARNESS_POLICY;
  const maxResultBytes = policy.maxToolResultBytes;
  const maxEvidenceBytes = policy.maxEvidenceBytesPerAttempt;
  const frozenIdentity = deepFreeze({ ...identity });
  const frozenMembers = deepFreeze(members.map((member) => ({ ...member })));
  const byMemberId = new Map(frozenMembers.map((member) => [member.memberId, member] as const));

  const records: LedgerEvidenceSource[] = [];
  const bySourceId = new Map<string, LedgerEvidenceSource>();
  let bytesUsed = 0;

  function memberFor(memberId: string): EvidenceLedgerMember | undefined {
    return byMemberId.get(memberId);
  }

  function snapshotMatches(member: EvidenceLedgerMember, snapshot: InvestigationSnapshotRef): boolean {
    return snapshot.repoId === member.repositoryId && snapshot.baseSha === member.baseSha && snapshot.headSha === member.headSha;
  }

  /** The single append path: every invariant is checked here, whatever the origin. */
  function append(member: EvidenceLedgerMember, pending: PendingRecord): RegistrationOutcome {
    const byteLength = utf8ByteLength(pending.exactContent);
    if (byteLength > maxResultBytes) {
      return refuse('exceedsResultBound', `Payload is ${byteLength} bytes; one tool result may return at most ${maxResultBytes}.`);
    }
    if (bytesUsed + byteLength > maxEvidenceBytes) {
      return refuse('evidenceBudgetExhausted', `Registering ${byteLength} bytes would exceed the ${maxEvidenceBytes}-byte evidence budget for this attempt.`);
    }
    for (const location of pending.locations) {
      if (normalizeEvidencePath(location.path) !== location.path) return refuse('invalidPath', `Location path is not normalized: ${location.path}`);
      if (!normalizeEvidenceRange(location.range.startLine, location.range.endLine)) {
        return refuse('invalidRange', `Location range is not a bounded positive line range: ${location.path}`);
      }
    }
    if (pending.path !== undefined && normalizeEvidencePath(pending.path) !== pending.path) {
      return refuse('invalidPath', `Source path is not normalized: ${pending.path}`);
    }
    if (pending.range && !normalizeEvidenceRange(pending.range.startLine, pending.range.endLine)) {
      return refuse('invalidRange', 'Source range is not a bounded positive line range.');
    }
    const sourceId = pending.sourceId ?? mintSourceId();
    if (bySourceId.has(sourceId)) return refuse('duplicateSourceId', `Source ${sourceId} is already in this ledger.`);

    const source: LedgerEvidenceSource = deepFreeze({
      sourceId,
      digest: sha256Hex(pending.exactContent),
      kind: pending.kind,
      repositoryId: member.repositoryId,
      baseSha: member.baseSha,
      headSha: member.headSha,
      revision: pending.revision,
      path: pending.path,
      range: pending.range,
      completeness: pending.completeness,
      citable: isCitableOrigin(pending.origin),
      exactContent: pending.exactContent,
      runId: frozenIdentity.runId,
      lineageId: frozenIdentity.lineageId,
      attempt: frozenIdentity.attempt,
      memberId: member.memberId,
      origin: pending.origin,
      trust: pending.trust,
      producedBy: pending.producedBy ?? evidenceProducerFor(pending.origin, member.investigationSourceKind ?? 'provider'),
      sequence: records.length + 1,
      locations: pending.locations.map((location) => ({ ...location, range: { ...location.range } })),
      byteLength,
      truncation: pending.truncation,
      snapshotContentDigest: pending.snapshotContentDigest,
      importedFromAttempt: pending.importedFromAttempt,
    });
    records.push(source);
    bySourceId.set(sourceId, source);
    bytesUsed += byteLength;
    return { ok: true, source };
  }

  /** Common gate for every provider-backed result: member known, snapshot pinned to it, and a model-visible state. */
  function admitResult<T>(
    memberId: string,
    result: InvestigationResult<T>,
  ): { ok: true; member: EvidenceLedgerMember; value: T; completeness: EvidenceCompleteness; truncation?: EvidenceTruncation } | Refusal {
    const member = memberFor(memberId);
    if (!member) return refuse('unknownMember', `Member ${memberId} is not part of this run.`);
    if (!snapshotMatches(member, result.snapshot)) {
      return refuse('snapshotMismatch', `Result is pinned to ${result.snapshot.repoId}@${result.snapshot.baseSha}..${result.snapshot.headSha}, not member ${memberId}'s snapshot.`);
    }
    const shape = completenessOf(result);
    if (!shape) return refuse('notModelVisible', `A "${result.state}" result carries no content the model can see.`);
    return { ok: true, member, value: (result as { value: T }).value, ...shape };
  }

  function isRefusal(value: { ok: boolean }): value is Refusal {
    return value.ok === false;
  }

  const ledger: EvidenceLedger = {
    identity: frozenIdentity,
    members: frozenMembers,
    member: memberFor,
    get: (sourceId) => bySourceId.get(sourceId),
    sources: () => [...records],
    revoke: (sourceId) => {
      const existing = bySourceId.get(sourceId);
      if (existing === undefined) return false;
      if (existing.revoked === true) return true;
      const revoked = deepFreeze({ ...existing, citable: false, revoked: true });
      const index = records.indexOf(existing);
      if (index >= 0) records[index] = revoked;
      bySourceId.set(sourceId, revoked);
      return true;
    },
    get size() {
      return records.length;
    },
    get bytesUsed() {
      return bytesUsed;
    },
    maxEvidenceBytes,

    registerDiffPage(memberId, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      const page = admitted.value;
      const path = normalizeEvidencePath(page.path);
      if (!path) return refuse('invalidPath', `Diff page path is not usable: ${String(page.path)}`);
      const locations: EvidenceLocation[] = [];
      for (const position of page.positions) {
        const positionPath = normalizeEvidencePath(position.path);
        const range = normalizeEvidenceRange(position.line, position.endLine);
        if (!positionPath) return refuse('invalidPath', `Diff position path is not usable: ${String(position.path)}`);
        if (!range) return refuse('invalidRange', `Diff position has an invalid line range at ${positionPath}.`);
        locations.push({ path: positionPath, range, side: position.side });
      }
      // A source that named its own positions has spoken; only silence is
      // answered from the patch (see `diffPatchLocations` for the live failure
      // that made a silent source mean "nothing here is citable").
      if (locations.length === 0) {
        const oldPath = page.oldPath === undefined ? path : normalizeEvidencePath(page.oldPath);
        if (!oldPath) return refuse('invalidPath', `Diff page old path is not usable: ${String(page.oldPath)}`);
        locations.push(...diffPatchLocations(page.patch, path, oldPath));
      }
      return append(admitted.member, {
        kind: 'diff',
        origin: 'diffPage',
        trust: 'untrusted',
        path,
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations,
        exactContent: page.patch,
      });
    },

    registerFileRange(memberId, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      const file = admitted.value;
      const path = normalizeEvidencePath(file.path);
      const range = normalizeEvidenceRange(file.startLine, file.endLine);
      if (!path) return refuse('invalidPath', `File range path is not usable: ${String(file.path)}`);
      if (!range) return refuse('invalidRange', `File range ${String(file.startLine)}-${String(file.endLine)} is not a bounded positive line range.`);
      return append(admitted.member, {
        kind: 'file',
        origin: 'fileRange',
        trust: 'untrusted',
        revision: file.revision,
        path,
        range,
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations: [{ path, range }],
        exactContent: file.text,
      });
    },

    registerRepositorySearch(memberId, request, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      if (!snapshotMatches(admitted.member, request.snapshot)) {
        return refuse('snapshotMismatch', 'Search request and result are pinned to different snapshots.');
      }
      const locations: EvidenceLocation[] = [];
      const canonicalMatches: Array<{ path: string; line: number; excerpt: string }> = [];
      for (const match of admitted.value) {
        const path = normalizeEvidencePath(match.path);
        const range = normalizeEvidenceRange(match.line);
        if (!path) return refuse('invalidPath', `Search match path is not usable: ${String(match.path)}`);
        if (!range) return refuse('invalidRange', `Search match line is invalid at ${path}.`);
        locations.push({ path, range });
        canonicalMatches.push({ path, line: match.line, excerpt: match.excerpt });
      }
      return append(admitted.member, {
        kind: 'searchExcerpt',
        origin: 'repositorySearch',
        trust: 'untrusted',
        revision: request.revision,
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations,
        exactContent: canonicalStringify(canonicalMatches),
      });
    },

    registerDiffSearch(memberId, request, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      if (!snapshotMatches(admitted.member, request.snapshot)) {
        return refuse('snapshotMismatch', 'Search request and result are pinned to different snapshots.');
      }
      const locations: EvidenceLocation[] = [];
      const canonicalMatches: Array<{ path: string; side: 'old' | 'new'; line: number; endLine?: number; excerpt: string }> = [];
      for (const match of admitted.value) {
        const path = normalizeEvidencePath(match.position.path);
        const range = normalizeEvidenceRange(match.position.line, match.position.endLine);
        if (!path) return refuse('invalidPath', `Diff search match path is not usable: ${String(match.position.path)}`);
        if (!range) return refuse('invalidRange', `Diff search match has an invalid line range at ${path}.`);
        locations.push({ path, range, side: match.position.side });
        canonicalMatches.push({ path, side: match.position.side, line: match.position.line, endLine: match.position.endLine, excerpt: match.excerpt });
      }
      return append(admitted.member, {
        kind: 'searchExcerpt',
        origin: 'diffSearch',
        trust: 'untrusted',
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations,
        exactContent: canonicalStringify(canonicalMatches),
      });
    },

    registerChangeRequestDetail(memberId, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      return append(admitted.member, {
        kind: 'detail',
        origin: 'changeRequestDetail',
        trust: 'untrusted',
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations: [],
        exactContent: canonicalStringify(admitted.value),
      });
    },

    registerIssueDetail(memberId, result) {
      const admitted = admitResult(memberId, result);
      if (isRefusal(admitted)) return admitted;
      return append(admitted.member, {
        kind: 'detail',
        origin: 'issueDetail',
        trust: 'untrusted',
        completeness: admitted.completeness,
        truncation: admitted.truncation,
        locations: [],
        exactContent: canonicalStringify(admitted.value),
      });
    },

    registerAgentsPolicy(memberId, level) {
      const member = memberFor(memberId);
      if (!member) return refuse('unknownMember', `Member ${memberId} is not part of this run.`);
      if (level.state !== 'present') return refuse('notModelVisible', `An "${level.state}" AGENTS.md level has no content.`);
      if (sha256Hex(level.content) !== level.digest) {
        return refuse('digestMismatch', 'AGENTS.md level digest does not match its content.');
      }
      const path = normalizeEvidencePath(level.directory === '' ? 'AGENTS.md' : `${level.directory}/AGENTS.md`);
      if (!path) return refuse('invalidPath', `AGENTS.md directory is not usable: ${level.directory}`);
      return append(member, {
        kind: 'file',
        origin: 'agentsPolicy',
        trust: 'authoritative',
        revision: 'base',
        path,
        completeness: 'complete',
        locations: [],
        exactContent: level.content,
      });
    },

    registerAttachment(memberId, attachment, snapshotContentDigest) {
      const member = memberFor(memberId);
      if (!member) return refuse('unknownMember', `Member ${memberId} is not part of this run.`);
      if (typeof attachment.content !== 'string') return refuse('malformed', 'Attachment has no content.');
      if (sha256Hex(attachment.content) !== snapshotContentDigest) {
        return refuse('digestMismatch', `Attachment ${attachment.id} does not match the content digest pinned in the run snapshot.`);
      }
      const visibleLength = Math.min(attachment.content.length, attachment.visibleContentLength ?? attachment.content.length);
      const exactContent = attachment.content.slice(0, visibleLength);
      const locations: EvidenceLocation[] = [];
      for (const entry of attachmentEvidenceManifest([attachment])) {
        const path = normalizeEvidencePath(entry.path);
        if (!path) return refuse('invalidPath', `Attachment evidence path is not usable: ${entry.path}`);
        for (const range of entry.ranges) {
          const normalized = normalizeEvidenceRange(range.startLine, range.endLine);
          if (!normalized) return refuse('invalidRange', `Attachment evidence range is invalid at ${path}.`);
          locations.push({ path, range: normalized });
        }
      }
      const path = normalizeEvidencePath(attachment.path);
      return append(member, {
        kind: 'attachment',
        origin: 'attachment',
        trust: 'untrusted',
        path,
        range: locations.length === 1 ? locations[0]?.range : undefined,
        completeness: visibleLength < attachment.content.length || attachment.truncated ? 'truncated' : 'complete',
        truncation: visibleLength < attachment.content.length || attachment.truncated ? { hasContinuation: false } : undefined,
        locations,
        exactContent,
        snapshotContentDigest,
      });
    },

    registerIntent(memberId, label, text) {
      const member = memberFor(memberId);
      if (!member) return refuse('unknownMember', `Member ${memberId} is not part of this run.`);
      if (typeof text !== 'string' || label.trim() === '') return refuse('malformed', 'Intent needs a label and text.');
      return append(member, {
        kind: 'detail',
        origin: 'intent',
        trust: 'untrusted',
        completeness: 'complete',
        locations: [],
        exactContent: canonicalStringify({ label, text }),
      });
    },

    importRetainedSource(record) {
      const member = memberFor(record.memberId);
      if (!member) return refuse('unknownMember', `Member ${record.memberId} is not part of this run.`);
      if (record.repositoryId !== member.repositoryId || record.baseSha !== member.baseSha || record.headSha !== member.headSha) {
        return refuse('snapshotMismatch', `Retained source ${record.sourceId} was fetched on a different repository or revision.`);
      }
      if (!isWellFormedSourceId(record.sourceId)) return refuse('malformed', 'Retained source identifier is not well-formed.');
      if (typeof record.exactContent !== 'string') {
        return refuse('exactContentUnavailable', `Retained source ${record.sourceId} has no exact content; it must be fetched again.`);
      }
      if (sha256Hex(record.exactContent) !== record.digest) {
        return refuse('digestMismatch', `Retained source ${record.sourceId} content no longer matches its digest.`);
      }
      if (!EVIDENCE_ORIGINS.includes(record.origin)) return refuse('malformed', `Unknown evidence origin: ${String(record.origin)}`);
      // Second line of defence for task 9.8, and one line of it: a resume
      // across a source-kind change is already refused whole by
      // `harnessResume.ts`, so this can only fire for a record assembled by
      // hand. It is worth the line anyway — importing keeps the prior
      // attempt's identifier, and an identifier that survives into a ledger
      // whose member is served by another source is evidence attributed to a
      // source that never produced it.
      const producedBy = evidenceProducerOf(record);
      if (producedBy !== evidenceProducerFor(record.origin, member.investigationSourceKind ?? 'provider')) {
        return refuse('snapshotMismatch', `Retained source ${record.sourceId} was produced by a different investigation source than this attempt's.`);
      }
      return append(member, {
        producedBy,
        sourceId: record.sourceId,
        kind: record.kind,
        origin: record.origin,
        trust: record.origin === 'agentsPolicy' ? 'authoritative' : 'untrusted',
        revision: record.revision,
        path: record.path,
        range: record.range,
        completeness: record.completeness,
        truncation: record.truncation,
        locations: record.locations,
        exactContent: record.exactContent,
        snapshotContentDigest: record.snapshotContentDigest,
        importedFromAttempt: record.fetchedInAttempt,
      });
    },
  };

  return ledger;
}

/** What section 11 may persist for one source: everything except (optionally) the exact bytes. */
export function toRetainedEvidenceRecord(source: LedgerEvidenceSource, options: { includeExactContent: boolean }): RetainedEvidenceRecord {
  return {
    sourceId: source.sourceId,
    digest: source.digest,
    kind: source.kind,
    origin: source.origin,
    memberId: source.memberId,
    repositoryId: source.repositoryId,
    baseSha: source.baseSha,
    headSha: source.headSha,
    revision: source.revision,
    path: source.path,
    range: source.range,
    completeness: source.completeness,
    locations: source.locations,
    truncation: source.truncation,
    snapshotContentDigest: source.snapshotContentDigest,
    fetchedInAttempt: source.importedFromAttempt ?? source.attempt,
    producedBy: source.producedBy,
    exactContent: options.includeExactContent ? source.exactContent : undefined,
  };
}
