/**
 * The append-only, per-attempt evidence ledger (tasks 7.1-7.4 of
 * `add-agentic-review-harness`, design.md D8, spec `review-evidence-ledger`).
 *
 * One ledger exists per harness attempt. It records every exact payload a
 * host tool returned to the model as a frozen `LedgerEvidenceSource`: the
 * D8 `EvidenceSource` fields (task 2.5) plus the binding task 7.2 requires —
 * run/lineage/attempt, changeset member, origin, trust, citable status, the
 * exact citable locations, byte length, and truncation metadata. Records are
 * never mutated, replaced, or removed: the only write operations append,
 * every returned record is deep-frozen, and `sources()` hands out a copy.
 *
 * Resolved design questions, so later sections do not re-litigate them:
 *
 * - **Exact bytes live in memory** (D8: "in-memory ledger ... `exactContent:
 *   string`"). Persisting only digests plus the excerpts retained citations
 *   need is section 11's `HarnessRunStore`, which reads from this ledger; the
 *   ledger itself never writes anywhere. `maxEvidenceBytesPerAttempt` from
 *   `HarnessPolicy` bounds the in-memory total, and a payload that does not
 *   fit is *refused* (nothing is returned to the model), never silently cut.
 * - **`sourceId` is opaque and unguessable**: `ev_` plus 128 random bits from
 *   `node:crypto`, generated by the ledger, never derived from path/range/
 *   content — so untrusted content cannot pre-compute a valid identifier and
 *   a citation cannot name a payload the model was never shown. Identifiers
 *   are attempt-bound by construction: they resolve only in the ledger that
 *   minted (or explicitly imported) them. D8's "stable inside the lineage"
 *   is `importRetainedSource`: a resumed attempt reuses the prior identifier
 *   only when the exact content is present and its digest and member
 *   snapshot still match; otherwise the new attempt must refetch.
 * - **Digest** is `sha256Hex` over the canonical bytes of what the model saw
 *   (`./contentDigest`): raw text for diff/file/attachment/policy/intent and
 *   sorted-key canonical JSON for structured search/detail payloads.
 * - **Citation authority is a source-category allowlist** (`CITABLE_ORIGINS`),
 *   not a per-record flag a caller can set: `citable` is derived from `origin`
 *   inside `append`, so intent, detail pages, and every `AGENTS.md` level are
 *   non-citable by construction (task 7.4, section-6 note in
 *   `harnessBootstrap.ts`), diff evidence and explicit attachments citable.
 * - **Only model-visible results register** (task 7.3): every provider-backed
 *   `register*` takes the neutral `InvestigationResult` and refuses any state
 *   without a `value` (`unavailable`, `binary`, `tooLarge`, `notFound`,
 *   `unknown`) — a partial or failed provider state can never become a
 *   citable record. The dispatcher (section 9) is expected to return
 *   `source.exactContent` to the model, so the bytes recorded and the bytes
 *   shown are the same string.
 * - **Cross-head / cross-member aliasing is rejected** at registration: a
 *   result whose `snapshot` differs from the declared member's repository,
 *   base, or head is refused, so evidence from another head can never sit
 *   under this attempt's identifiers (spec: "evidence from the two heads is
 *   never combined into one finding").
 *
 * - **Every record names the source that produced it** (`producedBy`,
 *   `add-local-git-investigation` task 10.1). Derived inside `append` from the
 *   origin and the member's recorded investigation source, never accepted from
 *   a caller, and carried through persistence so a resumed attempt and a
 *   diagnostics report read what the fetching attempt recorded rather than
 *   re-deriving it from whatever source is selected now.
 *
 * Trust: every author-controlled payload (diff, file, search, detail,
 * attachment, intent) is `untrusted`; `AGENTS.md` policy is `authoritative`
 * but non-citable — the same split `harnessBootstrap.ts` documents.
 */
